# frozen_string_literal: true

module ::TerrytrillaSeo
  # B14: тексты форума в `<title>` и описании — на языке страницы, на ЛЮБОЙ странице.
  #
  # Замер 19.09.2026 по пяти типам страниц × четыре языка показал, что перевод доезжает
  # не везде. У статьи и у «/about» всё на языке читателя, а у ленты (`/latest`, `/top`)
  # и у раздела заголовок и описание оставались английскими на всех двенадцати языках:
  # ядро берёт их из настройки и из названия раздела, а переводы лежат отдельно
  # (`SiteSettingLocalization`, `CategoryLocalization`) и в мета-теги не попадали.
  #
  # ⚠️ Точечные правки этот класс не закрывают: 18.09 так починили заголовок темы,
  # 19.09 — описание главной, и каждый раз оставались другие страницы. Поэтому подмена
  # стоит в ЕДИНСТВЕННОЙ точке, через которую ядро пропускает и заголовок, и описание
  # любой страницы, — модификатор `:meta_data_content` (`application_helper.rb:302`).
  # Новая страница и новый раздел попадают под правило сами.
  #
  # Заменяются ЦЕЛЫЕ куски, а не подстроки: заголовок ядро собирает через « - », а
  # описание приходит целиком. Подстрочная замена задела бы чужой текст — например,
  # слово «Questions» внутри заголовка темы.
  module SiteText
    # ⚠️ Переводы настроек ядро отдаёт ТОЛЬКО при включённой локализации содержимого:
    # `SiteSettingLocalization.value_for` иначе молча возвращает значение по умолчанию
    # (`site_setting_localization.rb:30`). Разделы читаются отсюда напрямую, и без этой
    # проверки они переводились бы при выключенной локализации, а описание сайта — нет.
    # Правило должно быть одно на все тексты.
    def self.active?
      SiteSetting.terrytrilla_seo_enabled && SiteSetting.content_localization_enabled
    end

    # Пары «текст по умолчанию → перевод» для одного языка. Строится из базы, а не из
    # списка в коде: раздел переименуют или добавят — таблица соберётся заново.
    #
    # ⚠️ Без кеша, и намеренно. Первая версия держала таблицу пять минут, и на ней
    # сразу покраснел спек: перевод, добавленный только что, не виден — сначала в
    # прогоне, а на форуме так же не увидели бы новый раздел или правку описания.
    # Цена запроса мала: одна строка настройки и десяток строк разделов на рендер.
    def self.таблица(locale)
      построить(locale.to_s)
    end

    def self.построить(locale)
      пары = {}
      добавить(пары, SiteSetting.site_description, перевод_настройки(:site_description, locale))

      CategoryLocalization
        .where(locale: locale)
        .includes(:category)
        .find_each do |локализация|
          раздел = локализация.category
          next if раздел.nil?
          добавить(пары, раздел.name, локализация.name)
          добавить(пары, раздел.description_text, локализация.description)
        end

      пары
    end

    def self.добавить(пары, оригинал, перевод)
      о = оригинал.to_s.strip
      п = перевод.to_s.strip
      return if о.blank? || п.blank? || о == п
      пары[о] = п
    end

    def self.перевод_настройки(имя, locale)
      SiteSettingLocalization.value_for(имя, locale: locale.to_s)
    rescue StandardError
      nil
    end

    def self.на_языке_страницы(строка, locale = I18n.locale)
      return строка unless active?
      текст = строка.to_s
      return строка if текст.blank?

      пары = таблица(locale)
      return строка if пары.empty?
      return пары[текст] if пары.key?(текст)

      части = текст.split(" - ")
      return строка if части.size < 2
      части.map { |часть| пары.fetch(часть.strip, часть) }.join(" - ")
    end

    # B17 (решение владельца 19.09, вариант B). Подзаголовок форума в заголовке
    # ГЛАВНОЙ — на языке страницы.
    #
    # Настройка ядра `short_site_description` для этого не годится: её значение
    # уезжает в клиентский набор настроек, а он кешируется на сайт, а не на язык, —
    # и ядро дописывало бы один и тот же английский текст всем (B15). Поэтому текст
    # живёт здесь, в переводах плагина: клиент его не видит, а сервер подставляет на
    # языке читателя. Слова взяты из утверждённого описания форума и глоссария.
    # ⚠️ Условие тут ДРУГОЕ, чем у подмены текстов из базы: подзаголовок лежит в
    # файлах перевода плагина, а не в `SiteSettingLocalization`, и локализация
    # содержимого ему не нужна. Общий `active?` давал пустую строку — поймал спек.
    def self.подзаголовок(locale = I18n.locale)
      return nil unless SiteSetting.terrytrilla_seo_enabled
      # ⚠️ Через `with_locale`, а не параметром `locale:`. У Discourse переводы
      # грузятся лениво, по текущему языку: с параметром спек получал пустую
      # строку на русском при существующем файле перевода.
      I18n.with_locale(locale) { I18n.t("terrytrilla_seo.tagline", default: nil) }.presence
    end

    # B19-бис: имя раздела ВНУТРИ заголовка страницы раздела.
    #
    # Замер 19.09 по четырём языкам: краулерная раскладка `/c/knowledge-base/10`
    # отдавала «最新 Knowledge Base トピック», «Aktuell in Knowledge Base»,
    # «Knowledge Base&nbsp;— Последние темы», «최신 Knowledge Base 주제». В браузере
    # там же «ナレッジベース» — то есть английское имя раздела видел ровно Google.
    #
    # Почему целая подмена (`на_языке_страницы`) это не ловит: ядро собирает строку
    # интерполяцией — `I18n.t("js.filters.with_category", filter:, category:)`
    # (`list_controller.rb:109`). Имя раздела лежит ВНУТРИ, целым куском строка ему
    # не равна, а делить по « - » тут нечего.
    #
    # ⚠️ Поэтому здесь — подстрочная замена, но с жёстким ограничением: меняется имя
    # ТОЛЬКО того раздела, чью страницу читатель открыл (id берётся из адреса), и
    # только один раз. Сплошная подстрочная замена по всем разделам задела бы чужой
    # текст — ровно от неё отказались в `на_языке_страницы` (слово «Questions»
    # внутри заголовка темы).
    АДРЕС_РАЗДЕЛА = %r{\A/c/(?:[^/?#]+/)*(\d+)(?:[/?#]|\z)}

    def self.заголовок_раздела(строка, путь, locale = I18n.locale)
      return строка unless SiteSetting.terrytrilla_seo_enabled
      ид = путь.to_s.split("?").first.to_s[АДРЕС_РАЗДЕЛА, 1]
      return строка if ид.blank?

      раздел = Category.find_by(id: ид.to_i)
      return строка if раздел.nil?
      имя = раздел.name.to_s
      return строка if имя.blank? || !строка.to_s.include?(имя)

      # ⚠️ Перевод берём тем же способом, что и ядро: `get_localization` знает про
      # разнопись языка (`pt_BR` против `pt-br`), а поиск по колонке `locale` — нет.
      return строка unless ContentLocalization.show_translated_category?(раздел, nil)
      перевод = раздел.get_localization(locale)&.name
      return строка if перевод.blank? || перевод == имя

      строка.sub(имя, перевод)
    rescue StandardError
      строка
    end

    # Заголовок главной: «Имя сообщества — подзаголовок». На остальных страницах
    # подзаголовка нет: там заголовок несёт тему или раздел.
    def self.заголовок_главной(строка, путь, locale = I18n.locale)
      return строка unless путь.to_s.split("?").first.to_s.chomp("/").empty?
      хвост = подзаголовок(locale)
      return строка if хвост.blank? || строка.to_s.include?(хвост)
      "#{строка} - #{хвост}"
    end
  end
end
